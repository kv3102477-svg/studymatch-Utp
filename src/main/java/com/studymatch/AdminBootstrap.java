package com.studymatch;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

@Configuration
public class AdminBootstrap {
    @Bean BCryptPasswordEncoder passwordEncoder() { return new BCryptPasswordEncoder(12); }

    @Bean CommandLineRunner inicializarAdmin(JdbcTemplate jdbc, BCryptPasswordEncoder encoder,
        @Value("${ADMIN_EMAIL:}") String email, @Value("${ADMIN_PASSWORD:}") String password,
        @Value("${ADMIN_NAME:Administrador StudyMatch}") String name) {
        return args -> {
            jdbc.execute("CREATE TABLE IF NOT EXISTS admin_usuario (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, correo VARCHAR(160) NOT NULL, nombre VARCHAR(120) NOT NULL, contrasena_hash VARCHAR(100) NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE, creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)");
            jdbc.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_admin_usuario_correo_lower ON admin_usuario (lower(correo))");
            jdbc.execute("CREATE TABLE IF NOT EXISTS admin_recuperacion (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT NOT NULL REFERENCES admin_usuario(id) ON DELETE CASCADE, token_hash CHAR(64) NOT NULL UNIQUE, expira_en TIMESTAMP WITHOUT TIME ZONE NOT NULL, usado BOOLEAN NOT NULL DEFAULT FALSE)");
            jdbc.execute("ALTER TABLE materia ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE");
            if (email.isBlank() && password.isBlank()) return;
            if (email.isBlank() || password.length() < 12)
                throw new IllegalStateException("Define ADMIN_EMAIL y ADMIN_PASSWORD (mínimo 12 caracteres).");
            Integer existe = jdbc.queryForObject("SELECT count(*) FROM admin_usuario WHERE lower(correo)=lower(?)", Integer.class, email.trim());
            if (existe == null || existe == 0)
                jdbc.update("INSERT INTO admin_usuario(correo,nombre,contrasena_hash) VALUES (?,?,?)",
                    email.trim().toLowerCase(), name.trim(), encoder.encode(password));
        };
    }
}
